const assert=require('node:assert/strict');
const fs=require('node:fs');
const {plan,detectShiftedRange,repair}=require('../rename-plan');
const rows=Array.from({length:331},(_,i)=>({shopId:`shop-${i}`,name:`Gross ${331+i}`,grossPerMin:i}));
const ordinary=plan(rows,'Gross {n}',331);
assert.equal(ordinary.changes.length,0,'normal rename keeps existing valid IDs');
const detected=detectShiftedRange([...rows].reverse(),'Gross {n}');
assert.equal(detected.first,331);assert.equal(detected.last,661);
assert.equal(Object.keys(detected.targets).length,331);
let preview=repair(rows,'Gross {n}',detected.targets);
assert.equal(preview.changes.length,331);
assert.equal(preview.changes[0].newName,'Gross 1');
assert.equal(preview.changes.at(-1).newName,'Gross 331');
for(const x of preview.changes.slice(0,100))x.shop.name=x.newName;
preview=repair([...rows].reverse(),'Gross {n}',detected.targets);
assert.equal(preview.changes.length,231,'resume only unfinished shops after an interrupted run');
assert.equal(preview.skipped,100);
const ids=new Set(preview.changes.map(x=>x.id));assert.equal(ids.size,231);
for(const x of preview.changes)x.shop.name=x.newName;
assert.equal(repair(rows,'Gross {n}',detected.targets).changes.length,0,'second repair run is idempotent');
assert.equal(plan(rows,'Gross {n}',331,detected.targets).changes.length,0,'normal planner also stays stable after completed repair');
const added={shopId:'shop-new',name:'New'};
assert.equal(plan([...rows,added],'Gross {n}',331,detected.targets).changes[0].newName,'Gross 332');
assert.equal(detectShiftedRange([...rows,added],'Gross {n}'),null);
assert.equal(detectShiftedRange([{id:'a',name:'Gross 106'},{id:'b',name:'Gross 107'}],'Gross {n}'),null,'do not suggest repair for a normal small persistent range');
const gaps=Array.from({length:15},(_,i)=>({id:`id${i}`,name:`Gross ${15+i+(i>7?1:0)}`}));
assert.equal(detectShiftedRange(gaps,'Gross {n}'),null,'gaps must not trigger a mass shift');
const duplicates=Array.from({length:15},(_,i)=>({id:`id${i}`,name:`Gross ${15+(i===14?13:i)}`}));
assert.equal(detectShiftedRange(duplicates,'Gross {n}'),null,'duplicate numbers must not trigger repair');
const badIds=Array.from({length:15},(_,i)=>({id:i===14?'id0':`id${i}`,name:`Gross ${15+i}`}));
assert.equal(detectShiftedRange(badIds,'Gross {n}'),null,'duplicate shop IDs must not trigger repair');
assert.equal(repair([...rows,{shopId:'new',name:'New'}],'Gross {n}',detected.targets).unresolved,1,'new shops outside staged plan remain untouched');
const ui=fs.readFileSync(require('node:path').join(__dirname,'../content.js'),'utf8');
assert.match(ui,/makeBulkPreview\(baseShopRows\(a\)\)/,'mass preview must include all shops regardless of search filters');
assert.match(ui,/crcc_gross_rebase_v1/,'interrupted repairs persist account-scoped targets');
console.log('PASS: 331 shifted Gross names, original IDs stable, explicit repair, partial resume, reorder, second run, new shop, gaps and duplicates');
(async()=>{
  const src=fs.readFileSync(require('node:path').join(__dirname,'../content.js'),'utf8');
  const vm=require('node:vm'),storage={};
  const state={renamePattern:'Gross {n}',renameStart:331,grossRebases:{},selected:new Set(),bulkPreview:[],bulkSkipped:0,bulkRepair:false,renameSortMode:'gross'};
  const ctx=vm.createContext({CRCCRename:require('../rename-plan'),state,console,Date,chrome:{storage:{local:{get:async()=>storage,set:async p=>Object.assign(storage,p)}}},account:()=>({id:'company-a',kind:'company'}),shopName:r=>r.name,render:()=>{},toast:()=>{}});
  vm.runInContext(src.slice(src.indexOf('  async function previewShiftedRange('),src.indexOf('  function parseCash(')),ctx);
  ctx.rows=Array.from({length:331},(_,i)=>({shopId:`live-${i}`,name:`Gross ${331+i}`}));
  await vm.runInContext('previewShiftedRange(rows)',ctx);
  assert.equal(state.bulkPreview.length,331);
  assert.equal(state.bulkRepair,true);
  assert.equal(storage.crcc_gross_rebase_v1['company:company-a'].targets['shopId:live-0'],1);
  assert.equal(storage.crcc_gross_ids_v1,undefined,'preview does not prematurely overwrite confirmed Gross IDs');
  for(let i=0;i<100;i++)ctx.rows[i].name=`Gross ${i+1}`;
  state.grossRebases=storage.crcc_gross_rebase_v1;
  await vm.runInContext('makeBulkPreview([...rows].reverse())',ctx);
  assert.equal(state.bulkPreview.length,231,'reloaded staged mapping resumes after partial rename');
  for(let i=100;i<331;i++)ctx.rows[i].name=`Gross ${i+1}`;
  await vm.runInContext('makeBulkPreview(rows)',ctx);
  assert.equal(state.bulkPreview.length,0);
  assert.equal(state.renameStart,1);
  assert.equal(storage.crcc_gross_rebase_v1['company:company-a'],undefined);
  assert.equal(storage.crcc_gross_ids_v1['company:company-a']['shopId:live-330'],331);
  console.log('PASS: UI stages account repair, preserves confirmed mappings until writes, resumes, and clears stage after completion');
})().catch(e=>{console.error(e);process.exitCode=1;});
